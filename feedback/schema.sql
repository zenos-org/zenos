CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, handle TEXT, name TEXT, via TEXT, joined INTEGER, young INTEGER DEFAULT 0, banned INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, user TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS oauth (state TEXT PRIMARY KEY, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS posts (id INTEGER PRIMARY KEY AUTOINCREMENT, thread TEXT NOT NULL, edition TEXT DEFAULT '', text TEXT NOT NULL, at INTEGER NOT NULL,
  user TEXT NOT NULL, staff INTEGER DEFAULT 0, reply INTEGER, proposal INTEGER, ai TEXT DEFAULT '', hidden INTEGER DEFAULT 0, held TEXT DEFAULT '',
  checked INTEGER DEFAULT 0, reviewed INTEGER DEFAULT 0, byai INTEGER DEFAULT 0);
CREATE INDEX IF NOT EXISTS posts_thread ON posts (thread, reply);
CREATE INDEX IF NOT EXISTS posts_edition ON posts (edition, reply);
CREATE INDEX IF NOT EXISTS posts_user ON posts (user, at);
CREATE INDEX IF NOT EXISTS posts_reply ON posts (reply);
CREATE TABLE IF NOT EXISTS metoo (post INTEGER NOT NULL, user TEXT NOT NULL, PRIMARY KEY (post, user));
CREATE TABLE IF NOT EXISTS proposals (id INTEGER PRIMARY KEY AUTOINCREMENT, created INTEGER, thread TEXT, edition TEXT DEFAULT '', title TEXT, asked TEXT, where_ TEXT,
  change TEXT DEFAULT '', risk TEXT DEFAULT '', status TEXT DEFAULT 'proposed', note TEXT DEFAULT '', pr TEXT DEFAULT '', release TEXT DEFAULT '',
  by_ TEXT DEFAULT 'local', security INTEGER DEFAULT 0, route TEXT DEFAULT '', decided INTEGER);
CREATE TABLE IF NOT EXISTS proposal_posts (proposal INTEGER NOT NULL, post INTEGER NOT NULL, PRIMARY KEY (proposal, post));
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
